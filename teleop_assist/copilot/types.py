"""Data contracts for orientation assistance before the existing arm IK.

Transforms are T_base_ee in metres. Times are acquisition times in an explicitly
named clock; receipt time is deliberately not a substitute. Validation flags
refer to the candidate pose in the containing batch's observation/calibration.
They are evidence supplied by the caller, never generated by this controller.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

import numpy as np


@dataclass(frozen=True)
class OperatorSample:
    left_base_ee: np.ndarray
    right_base_ee: np.ndarray
    acquisition_timestamp: float | None
    clock_id: str | None
    tracking_valid: bool


@dataclass(frozen=True)
class GraspCandidate:
    candidate_id: str
    base_ee: np.ndarray
    model_score: float
    geometry_valid: bool = False
    ik_valid: bool = False
    collision_valid: bool = False
    source: str = ""


@dataclass(frozen=True)
class ProposalBatch:
    target_id: str
    observation_id: str
    capture_timestamp: float | None
    clock_id: str | None
    calibration_id: str
    candidates: tuple[GraspCandidate, ...]
    # Explicit upstream statement for a stationary-target approach. A new
    # timestamp alone is not evidence that an object has remained stationary.
    motion_static: bool = False
    valid: bool = False
    # Optional explicit frozen-inference binding. observation_id/capture_timestamp
    # still name the current independent validation, never retimed inference.
    model_source_id: str | None = None
    model_source_capture_timestamp: float | None = None
    # Archived inference can originate from a different host boot. Its clock
    # is provenance only; current validation still must use clock_id above.
    model_source_clock_id: str | None = None


@dataclass(frozen=True)
class PreviewSelection:
    """Inert live choice, never an endpoint batch or motion capability.

    The pose is an immutable tuple copied from the observed preview. Source
    stays raw; the later endpoint batch binds it to model_source_id separately.
    UI and object signatures bind this staging record to one deliberate edge.
    """
    target_id: str
    target_revision: int
    target_signature: str
    observation_id: str
    capture_timestamp: float
    clock_id: str
    calibration_id: str
    candidate_id: str
    base_ee: tuple[tuple[float, ...], ...]
    model_score: float
    source: str
    model_source_id: str
    model_source_capture_timestamp: float
    model_source_clock_id: str
    ui_revision: int
    ui_signature: str
    ui_client_id: str


@dataclass(frozen=True)
class CopilotRequest:
    select_candidate_id: str | None = None
    confirm: bool = False
    assist_held: bool = False
    release: bool = False


@dataclass(frozen=True)
class CopilotConfig:
    input_max_age_s: float = 0.15
    target_max_age_s: float = 0.5
    future_tolerance_s: float = 0.01
    max_step_s: float = 0.2
    max_orientation_correction_rad: float = np.deg2rad(20.0)
    offset_rate_rad_s: float = np.deg2rad(30.0)
    max_offset_increment_rad: float = np.deg2rad(1.0)
    counterrotation_window_s: float = 0.3
    counterrotation_threshold_rad: float = np.deg2rad(8.0)
    counterrotation_min_speed_rad_s: float = np.deg2rad(20.0)

    def __post_init__(self):
        values = np.array(list(vars(self).values()), dtype=float)
        if (not np.isfinite(values).all() or np.any(values < 0)
                or self.input_max_age_s <= 0 or self.target_max_age_s <= 0
                or self.max_step_s <= 0 or self.offset_rate_rad_s <= 0
                or not 0 < self.max_offset_increment_rad <= self.max_orientation_correction_rad
                or self.counterrotation_window_s <= 0
                or self.counterrotation_threshold_rad <= 0
                or not 0 < self.max_orientation_correction_rad < np.pi / 2):
            raise ValueError("Invalid copilot configuration")


@dataclass(frozen=True)
class CopilotResult:
    left_base_ee: np.ndarray
    right_base_ee: np.ndarray
    preview_right_base_ee: np.ndarray | None
    input_hold_required: bool
    applied: bool
    reason: str
    snapshot: dict[str, Any] = field(default_factory=dict)
